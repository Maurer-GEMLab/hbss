"""Dataset fetching.

Data never lives in the repository. ``registry.yaml`` maps logical dataset
names to URI, checksum, size, and provenance; this module resolves a name and
populates ``$HBSS_DATA_ROOT``.

Test fixtures are <= 5 MB and generated by :mod:`hbss.simulate` wherever
possible, so that the test suite does not depend on the data store.

Status: skeleton. Phase 0 -- the storage location decision is a Phase 0 blocker.
"""

from __future__ import annotations

import argparse
import sys


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="hbss-fetch", description=__doc__)
    parser.add_argument("dataset", help="logical dataset name from registry.yaml")
    parser.parse_args(argv)
    print("hbss-fetch: not implemented yet (Phase 0)", file=sys.stderr)
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
